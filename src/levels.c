//
//   .  grass           #  stone wall      T  tree          ~  water
//   ^  thorns (hurt)   o  seed            k  key           D  door (needs a key)
//   h  heart           X  portal (exit)   P  player start
//   b  beetle (wanders)                   s  slime (follows you, takes 2 hits)
//
// A map needs one 'P' and one 'X', at most 64 rows and 96 columns. Keep
// keys outside locked rooms (or as many keys as doors), so the player can
// never use them up in the wrong order. tests/test_game.c checks that every
// seed, key and the portal can be reached.
