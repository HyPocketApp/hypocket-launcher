#!/usr/bin/env python3
"""Writes blocks/game/generated.h: what the game's own screens (screens.c,
used by the PC version) need from the Android side, so there is one source
for each thing:

- every string in res/values/strings.xml and res/values-pt-rBR/strings.xml
  (string arrays too), with Android's positional formats (%1$d) turned into
  plain C ones (%d), which needs the arguments in order in both languages;
- the things carried (BuildBlock in BlocksPalette.kt): name, colours, kind;
- the recipes (BlocksRecipes.kt);
- the story's notes (StoryNotes.kt).

Run by build.sh. With --check it only says whether generated.h is current.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent
MAIN = GAME.parent / "src" / "main"
KOTLIN = MAIN / "kotlin" / "io" / "github" / "hypocketapp" / "blocks"
OUT = GAME / "generated.h"


def android_text(raw):
    text = raw or ""
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            n = text[i + 1]
            out.append({"n": "\n", "t": "\t"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def c_format(name, text):
    """%1$d %2$s -> %d %s, if the arguments come in order."""
    numbers = [int(m) for m in re.findall(r"%(\d+)\$", text)]
    if numbers != sorted(numbers):
        sys.exit(f"gen_tables: {name}: arguments out of order ({text!r}); C has no positional arguments")
    return re.sub(r"%\d+\$", "%", text)


def load_strings(path):
    root = ET.parse(path).getroot()
    strings, arrays = {}, {}
    for node in root:
        name = node.get("name")
        if node.tag == "string":
            strings[name] = c_format(name, android_text("".join(node.itertext())))
        elif node.tag == "string-array":
            arrays[name] = [c_format(name, android_text("".join(i.itertext()))) for i in node.findall("item")]
    return strings, arrays


def c_string(text):
    s = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return f'"{s}"'


def things():
    src = (KOTLIN / "ui" / "BlocksPalette.kt").read_text()
    body = src[src.index("enum class BuildBlock("):src.index("enum class Kind")]
    rows = re.findall(
        r"^\s+([A-Z_]+)\(R\.string\.(\w+), Color\(0x([0-9A-Fa-f]{8})\), Color\(0x([0-9A-Fa-f]{8})\)(?:, Kind\.(\w+))?\),",
        body, re.M)
    if not rows:
        sys.exit("gen_tables: no things found in BlocksPalette.kt")
    return [(n, label, int(c, 16), int(a, 16), kind or "BLOCK") for n, label, c, a, kind in rows]


def recipes(names):
    src = (KOTLIN / "BlocksRecipes.kt").read_text()
    body = src[src.index("val ALL: List<Recipe> = listOf("):src.index("val NATURAL")]
    out = []
    for m in re.finditer(r"Recipe\(listOf\(([^)]*)\), BuildBlock\.(\w+), (\d+)((?:, \w+ = BuildBlock\.\w+)*)\)", body):
        inputs = re.findall(r"BuildBlock\.(\w+) to (\d+)", m.group(1))
        extra = dict(re.findall(r"(\w+) = BuildBlock\.(\w+)", m.group(4)))
        ins = [(names.index(b), int(n)) for b, n in inputs] + [(-1, 0)] * (2 - len(inputs))
        out.append((ins, names.index(m.group(2)), int(m.group(3)),
                    names.index(extra["station"]) if "station" in extra else -1,
                    names.index(extra["tool"]) if "tool" in extra else -1))
    if len(out) != body.count("Recipe("):
        sys.exit("gen_tables: a recipe in BlocksRecipes.kt was not understood")
    return out


def notes():
    src = (KOTLIN / "StoryNotes.kt").read_text()
    rows = re.findall(r"Note\((\d+), Kind\.(\w+), R\.string\.(\w+), (text|chat) = R\.(?:string|array)\.(\w+)\)", src)
    return [(int(i), kind, title, field, body) for i, kind, title, field, body in rows]


def generate():
    en, en_arrays = load_strings(MAIN / "res" / "values" / "strings.xml")
    pt, pt_arrays = load_strings(MAIN / "res" / "values-pt-rBR" / "strings.xml")
    names = list(en)
    lines = [
        "/* Generated by tools/gen_tables.py from the Android strings, BlocksPalette.kt,",
        " * BlocksRecipes.kt and StoryNotes.kt. Do not edit: change those and run build.sh. */",
        "#ifndef BLOCKS_GENERATED_H",
        "#define BLOCKS_GENERATED_H",
        "",
        "enum {",
    ]
    lines += [f"    STR_{n}," for n in names]
    lines += ["    STR_COUNT", "};", ""]
    for lang, table in (("en", en), ("pt", pt)):
        lines.append(f"static const char* const strings_{lang}[STR_COUNT] = {{")
        lines += [f"    {c_string(table.get(n, en[n]))}," for n in names]
        lines += ["};", ""]
    array_names = list(en_arrays)
    lines.append("enum {")
    lines += [f"    STRA_{n}," for n in array_names]
    lines += ["    STRA_COUNT", "};", ""]
    for lang, table in (("en", en_arrays), ("pt", pt_arrays)):
        for n in array_names:
            items = table.get(n, en_arrays[n])
            lines.append(f"static const char* const {lang}_{n}[] = {{" + ", ".join(c_string(i) for i in items) + ", 0};")
        lines.append(f"static const char* const* const arrays_{lang}[STRA_COUNT] = {{" +
                     ", ".join(f"{lang}_{n}" for n in array_names) + "};")
        lines.append("")

    rows = things()
    thing_names = [r[0] for r in rows]
    kinds = ["BLOCK", "MATERIAL", "TOOL", "FOOD", "CLOTHING"]
    lines += [
        "enum { THING_BLOCK, THING_MATERIAL, THING_TOOL, THING_FOOD, THING_CLOTHING };",
        "",
        "typedef struct {",
        "    int label;               /* STR_* */",
        "    uint32_t color, accent;  /* 0xAARRGGBB */",
        "    int kind;                /* THING_* */",
        "} UiThing;",
        "",
        f"#define UI_THINGS {len(rows)}",
        "static const UiThing ui_things[UI_THINGS] = { /* in palette order */",
    ]
    lines += [f"    {{STR_{label}, 0x{c:08X}u, 0x{a:08X}u, THING_{kind}}}, /* {n} */" for n, label, c, a, kind in rows]
    lines += ["};", ""]
    lines.append("/* Their names in data packs and scripts (BuildBlock's, lower case). */")
    lines.append("static const char* const ui_thing_names[UI_THINGS] = {" + ", ".join(c_string(n.lower()) for n in thing_names) + "};")
    lines.append("")
    lines += [
        "typedef struct {",
        "    int8_t input[2], amount[2]; /* palette indices (-1: none) and how many */",
        "    int8_t output, count;",
        "    int8_t station, tool;       /* palette indices, -1: none */",
        "} UiRecipe;",
        "",
    ]
    rec = recipes(thing_names)
    lines.append(f"#define UI_RECIPES {len(rec)}")
    lines.append("static const UiRecipe ui_recipes[UI_RECIPES] = {")
    for ins, out, count, station, tool in rec:
        lines.append(f"    {{{{{ins[0][0]}, {ins[1][0]}}}, {{{ins[0][1]}, {ins[1][1]}}}, {out}, {count}, {station}, {tool}}},")
    lines += ["};", ""]
    lines += [
        "typedef struct {",
        "    int id, phone;           /* a phone shows a chat, else a paper's text */",
        "    int title, text;         /* STR_*; text is STRA_* for a phone */",
        "} UiNote;",
        "",
    ]
    ns = notes()
    lines.append(f"#define UI_NOTES {len(ns)}")
    lines.append("static const UiNote ui_notes[UI_NOTES] = {")
    for i, kind, title, field, body in ns:
        lines.append(f"    {{{i}, {1 if kind == 'PHONE' else 0}, STR_{title}, {'STRA_' if field == 'chat' else 'STR_'}{body}}},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            sys.exit("gen_tables: generated.h is out of date; run blocks/game/build.sh")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
