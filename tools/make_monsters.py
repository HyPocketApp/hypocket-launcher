def draw(art, palette, name):
    rows = [r for r in art.strip('\n').split('\n')]
    w = len(rows[0])
    for i, r in enumerate(rows):
        assert len(r) == w, '%s row %d is %d wide, not %d' % (name, i, len(r), w)
    img = Image.new('RGBA', (w, len(rows)), (0, 0, 0, 0))
    px = img.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != '.':
                px[x, y] = palette[ch] + (255,)
    img.save(os.path.join(OUT, name + '.png'), optimize=True)


def main():
    os.makedirs(OUT, exist_ok=True)
    draw(SLIME_1, SLIME, 'slime_1')
    draw(SLIME_2, SLIME, 'slime_2')
    draw(BEETLE_1, BEETLE, 'beetle_1')
    draw(BEETLE_2, BEETLE, 'beetle_2')
    draw(WOLF_1, WOLF, 'wolf_1')
    draw(WOLF_2, WOLF, 'wolf_2')
    print('wrote monsters to', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
